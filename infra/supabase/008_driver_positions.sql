-- Torre de controle: posição periódica do motorista enquanto há viagem em rota.
-- O aplicativo do motorista envia no máximo uma posição a cada 15 segundos e
-- somente com viagem liberada. Histórico mantido por 30 dias (limpeza na gravação).

BEGIN;

CREATE TABLE IF NOT EXISTS app.driver_positions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES app.drivers(id),
    trip_id bigint REFERENCES app.trips(id),
    latitude numeric(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude numeric(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    accuracy_m numeric(8,1) NOT NULL CHECK (accuracy_m BETWEEN 0 AND 10000),
    speed_kmh numeric(5,1) CHECK (speed_kmh IS NULL OR speed_kmh BETWEEN 0 AND 300),
    heading numeric(4,1) CHECK (heading IS NULL OR heading BETWEEN 0 AND 360),
    recorded_at timestamptz NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS driver_positions_by_driver
    ON app.driver_positions(driver_id, received_at DESC);
CREATE INDEX IF NOT EXISTS driver_positions_by_received_at
    ON app.driver_positions(received_at);

ALTER TABLE app.driver_positions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE app.driver_positions FROM PUBLIC, anon, authenticated;

COMMIT;

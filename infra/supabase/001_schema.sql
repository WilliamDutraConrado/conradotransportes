-- Conrado Entregas: esquema PostgreSQL inicial, preparado para Supabase.
-- Executar somente no projeto de desenvolvimento após conferir conexões e backups.
-- O esquema 'app' NÃO deve ser incluído nas schemas expostas pelo PostgREST.

BEGIN;

CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.drivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 100),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate varchar(7) UNIQUE NOT NULL CHECK (plate ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    vehicle_type varchar(30) NOT NULL,
    driver_id bigint NOT NULL REFERENCES app.drivers(id),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.trips (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES app.vehicles(id),
    driver_id bigint NOT NULL REFERENCES app.drivers(id),
    label varchar(120) NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','released','closed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    released_at timestamptz,
    closed_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS trips_one_released_vehicle
    ON app.trips(vehicle_id) WHERE status = 'released';

CREATE TABLE IF NOT EXISTS app.notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id bigint NOT NULL REFERENCES app.trips(id),
    access_key char(44) NOT NULL CHECK (access_key ~ '^[0-9]{44}$'),
    number varchar(20) NOT NULL,
    recipient_id varchar(20) NOT NULL,
    recipient text NOT NULL,
    address text NOT NULL,
    city varchar(100) NOT NULL DEFAULT '',
    seller varchar(100) NOT NULL DEFAULT '',
    items jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(items) = 'array'),
    gross_weight numeric(14,3) NOT NULL DEFAULT 0,
    volumes integer NOT NULL DEFAULT 0,
    status varchar(12) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','delivered','partial','refused','occurrence')),
    UNIQUE(trip_id,access_key)
);
CREATE INDEX IF NOT EXISTS notes_trip_status ON app.notes(trip_id,status);

CREATE TABLE IF NOT EXISTS app.driver_auth (
    driver_id bigint PRIMARY KEY REFERENCES app.drivers(id),
    salt varchar(32) NOT NULL,
    password_hash varchar(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS app.admin_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) UNIQUE NOT NULL CHECK (username ~ '^[a-z0-9._-]{3,50}$'),
    salt varchar(32) NOT NULL,
    password_hash varchar(64) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'operator'
        CHECK (role IN ('admin','operator','auditor')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.admin_sessions (
    token_hash varchar(64) PRIMARY KEY,
    admin_id bigint NOT NULL REFERENCES app.admin_users(id),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS admin_sessions_by_user ON app.admin_sessions(admin_id);

CREATE TABLE IF NOT EXISTS app.driver_sessions (
    token_hash varchar(64) PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES app.drivers(id),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_by_driver ON app.driver_sessions(driver_id);

-- Limitador persistente: armazena apenas hashes de IP e placa, nunca os valores em claro.
CREATE TABLE IF NOT EXISTS app.login_limits (
    key_hash char(64) PRIMARY KEY,
    failures smallint NOT NULL DEFAULT 0 CHECK (failures BETWEEN 0 AND 100),
    window_started timestamptz NOT NULL DEFAULT now(),
    blocked_until timestamptz
);

CREATE TABLE IF NOT EXISTS app.delivery_events (
    id varchar(90) PRIMARY KEY,
    note_id bigint NOT NULL REFERENCES app.notes(id),
    driver_id bigint NOT NULL REFERENCES app.drivers(id),
    status varchar(12) NOT NULL CHECK (status IN ('delivered','partial','refused','occurrence')),
    reason varchar(1000) NOT NULL DEFAULT '',
    arrival_time varchar(5) NOT NULL DEFAULT '',
    affected_item varchar(500) NOT NULL DEFAULT '',
    seller_name varchar(100) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

-- As fotos ficarão em um bucket PRIVADO do Supabase Storage, não no PostgreSQL.
CREATE TABLE IF NOT EXISTS app.evidence (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id bigint NOT NULL REFERENCES app.notes(id),
    event_id varchar(90) NOT NULL REFERENCES app.delivery_events(id),
    storage_path text NOT NULL UNIQUE,
    mime varchar(30) NOT NULL CHECK (mime IN ('image/jpeg','image/png')),
    sha256 char(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    happened_at timestamptz NOT NULL DEFAULT now(),
    actor varchar(100) NOT NULL,
    event varchar(100) NOT NULL,
    object_type varchar(50) NOT NULL,
    object_id bigint NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb
);

-- Defesa em profundidade: nunca expor tabelas diretamente ao cliente/mobile.
ALTER TABLE app.drivers ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.trips ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.driver_auth ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.admin_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.driver_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.login_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.delivery_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.audit ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON SCHEMA app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA app FROM PUBLIC, anon, authenticated;

COMMIT;
